// Imports the playable slice of Arsenal Forge into the game.
// Usage: node tools/import-arsenal.mjs <path-to-Aresenal-Forge>
// Copies each weapon's LOD 1 and LOD 2 GLB (LOD 0 is review geometry, 0.2-2.4 MB each, and stays upstream),
// the weapon and armor preview stills, and writes shared/arsenal.generated.js from the pack manifest.
// Every copied file is checked against the manifest's own SHA-256 before it is written.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const source = process.argv[2];
if (!source || !fs.existsSync(path.join(source, 'public/assets/manifest.json'))) throw new Error('Pass the Arsenal Forge checkout path');
const root = new URL('../', import.meta.url);
const commit = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const manifest = JSON.parse(fs.readFileSync(path.join(source, 'public/assets/manifest.json')));
const briefs = new Map(JSON.parse(fs.readFileSync(path.join(source, 'data/weapons.75.json'))).map((w) => [w.id, w]));
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
const out = new URL('game/public/assets/arsenal/', root);
fs.rmSync(out, { recursive: true, force: true });
const copy = (from, to, expected) => {
  const bytes = fs.readFileSync(path.join(source, 'public', from));
  if (expected && sha(bytes) !== expected) throw new Error(`Checksum mismatch: ${from}`);
  const target = new URL(to, out);
  fs.mkdirSync(new URL('./', target), { recursive: true });
  fs.writeFileSync(target, bytes);
  return bytes.length;
};
const round = (n) => Math.round(n * 1000) / 1000;
const previewOf = (id) => `previews/${id.slice('arsenal:'.length).replace(/\//g, '-')}.webp`;
const weapons = {}, armor = {};
let bytes = 0;
for (const asset of manifest.assets) {
  if (asset.kind !== 'weapons' && asset.kind !== 'armor') continue;
  const key = asset.id.slice('arsenal:'.length);
  bytes += copy(`assets/previews/arsenal-${key.replace(/\//g, '-')}.webp`, previewOf(asset.id));
  if (asset.kind === 'armor') {
    armor[asset.id] = { slot: asset.family, dims: asset.dimensionsMeters.map(round), preview: previewOf(asset.id) };
    continue;
  }
  const lods = {};
  for (const lod of asset.lods ?? []) {
    const rel = `weapons/${key}.lod${lod.level}.glb`;
    bytes += copy(lod.path, rel, lod.sha256);
    lods[lod.level] = { path: rel, triangles: lod.triangles, bytes: lod.bytes };
  }
  if (!lods[1] || !lods[2]) throw new Error(`Weapon without LOD 1/2: ${asset.id}`);
  const sockets = ['grip.primary', 'grip.secondary', 'holster', 'edge.base', 'edge.tip', 'vfx.muzzle']
    .filter((name) => asset.nodes.includes(name) && !(asset.unavailableSockets ?? []).includes(name));
  weapons[asset.id] = {
    name: asset.name, family: asset.family, hit: briefs.get(asset.id)?.geometry?.hitProfile ?? null,
    dims: asset.dimensionsMeters.map(round), sockets, lods, preview: previewOf(asset.id),
  };
}
if (Object.keys(weapons).length !== 75 || Object.keys(armor).length !== 60) throw new Error('Expected 75 weapons and 60 armor pieces');
fs.copyFileSync(path.join(source, 'docs/ASSET_PROVENANCE.md'), new URL('PROVENANCE.md', out));
const header = `// GENERATED by tools/import-arsenal.mjs from jrmoyler/Aresenal-Forge@${commit}. Do not edit by hand.\n`
  + '// Review geometry only: upstream marks 0 of 595 records as approved shipping art.\n';
fs.writeFileSync(new URL('shared/arsenal.generated.js', root), header
  + `export const ARSENAL_COMMIT = ${JSON.stringify(commit)};\n`
  + `export const ARSENAL_REVISION = ${JSON.stringify(manifest.assets.find((a) => a.artworkRevision)?.artworkRevision ?? null)};\n`
  + `export const ARSENAL_WEAPONS = ${JSON.stringify(weapons, null, 1)};\n`
  + `export const ARSENAL_ARMOR = ${JSON.stringify(armor, null, 1)};\n`);
console.log(commit, Object.keys(weapons).length, 'weapons', Object.keys(armor).length, 'armor', (bytes / 1e6).toFixed(1), 'MB');
