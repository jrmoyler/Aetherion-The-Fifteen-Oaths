// Extract renderer-independent VFX settings from both pinned Ability-Matrix sources.
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';

export function generatePalettes(...sources) {
  const palettes = {};
  for (const source of sources) {
    if (!/^[a-f0-9]{40}$/.test(source.sourceCommit)) throw new Error('Palette source must be pinned');
    for (const entry of source.castables) {
      const id = entry.sourceCatalog.uid;
      if (entry.sourcePreset.uid !== id || palettes[id]) throw new Error(`Invalid palette identity: ${id}`);
      const settings = entry.sourcePreset.settings;
      const colors = [...new Set(Object.values(settings).filter(value => typeof value === 'string' && /^#[0-9a-f]{6}$/i.test(value)))].slice(0, 8);
      if (!colors.length) throw new Error(`Missing source colors: ${id}`);
      const palette = { c: colors };
      for (const [sourceKey, key] of [['lifetime', 'l'], ['fade', 'f'], ['speed', 's']]) {
        const value = settings[sourceKey];
        if (value === undefined) continue;
        if (!Number.isFinite(value) || value < 0) throw new Error(`Invalid ${sourceKey}: ${id}`);
        palette[key] = value;
      }
      palettes[id] = palette;
    }
  }
  return palettes;
}

export function renderPalettes(...sources) {
  return '// GENERATED by tools/generate-ability-palettes.mjs from CASTABLE_REGISTRY.json and shared/ability-supplement.json.\n'
    + '// Source colors in authored order (c), lifetime (l), fade (f), speed (s); renderer-independent.\n'
    + `export const PALETTES = ${JSON.stringify(generatePalettes(...sources))};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const read = path => JSON.parse(fs.readFileSync(new URL(path, import.meta.url)));
  const output = renderPalettes(read('../CASTABLE_REGISTRY.json'), read('../shared/ability-supplement.json'));
  const target = new URL('../game/src/vfx/palettes.generated.js', import.meta.url);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Ability palettes stale; run node tools/generate-ability-palettes.mjs');
  } else fs.writeFileSync(target, output);
}
